#!/usr/bin/env python3
"""mkmus_ay.py -- FujiBlast's in-play music (music/play.txt, tools/mus.py)
for the NABU's AY-3-8910 (src/nabu/sound.c, mus_step). The AY has a third
channel the effects and jingles leave alone, so ch1 (the bass, the kick as
a falling thump; snare and hat on the noise) is all channel C's, and ch2
(the robots' chatter) is channel A's, between jingles. The SMS's converter
(tools/mkmus_sms.py) is the model: the same voices, the same volumes.

Each channel of a pattern is a list of steps (the same data once), each
channel's order a list of them; both go back to the song's loop together.
A step is 4 bytes, ended by one whose jiffies are 0:

    lo  hi  volume  jiffies     a tone: period hi << 8 | lo (12 bits)
    p   $80 volume  jiffies     channel C's noise, period p (the drums)
    0   0   0       jiffies     silence

Tone: f = 1789773 / (16 N), N 1-4095, down to 27 Hz: the bass can be where
it's written, but a TV's speaker hardly gives E1's 41 Hz, so it goes up
OCTAVES (default 1). Volume 0-15 (15 loud: the SN76489's attenuation from
15, as src/nabu/sound.c's effects).

usage: mkmus_ay.py music/play.txt OUTDIR [OCTAVES]   (writes OUTDIR/music.c)"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mus  # noqa: E402

AY = 1789773.0
MAXN = 252

# the drums' noise periods (1-31: higher is lower)
NOISE = {"S": 14, "H": 3}
# the NES's volume 0-6 as an AY volume (mkmus_sms.py's attenuations, from 15)
VOL = {0: 0, 1: 3, 2: 5, 3: 6, 4: 7, 5: 8, 6: 9}
BASS_VOL = 13


def tone_n(hz):
    n = round(AY / (16 * hz))
    if n > 4095:
        raise SystemExit("mkmus_ay: %.1f Hz is below the AY's 27 Hz" % hz)
    return max(2, n)


def tone(hz, v):
    n = tone_n(hz)
    return (n & 255, n >> 8, v)


def vol(k, steps):
    for until, v in steps:
        if k < until:
            return v
    return steps[-1][1]


def chat(hz, v):
    return (0, 0, 0) if v == 0 else tone(hz, VOL[v])


def ch1(ev, octaves):
    if ev is None:
        return (0, 0, 0)
    kind, note, k = ev
    if kind == "K":                     # a falling thump
        return tone((220.0, 110.0)[k], 13)
    if kind == "S":
        return (NOISE["S"], 0x80, (12, 9, 9)[k])
    if kind == "H":
        return (NOISE["H"], 0x80, 7)
    if kind == "bass":
        return tone(mus.hz(note) * 2 ** octaves, BASS_VOL)
    raise SystemExit("no ch1 voice for %r" % kind)


def ch2(ev):
    if ev is None:
        return (0, 0, 0)
    kind, note, k = ev
    hz = mus.hz(note)
    if kind == "blip":
        return chat(hz, vol(k, ((2, 6), (4, 3), (999, 0))))
    if kind == "tone":
        return chat(hz, vol(k, ((2, 6), (999, 4))))
    if kind in ("arp", "arpmaj", "warble"):
        return chat(hz, 5)
    k &= ~1                             # slides: a step every other jiffy
    if kind == "sweep":
        return chat(max(125.0, hz / 1.08 ** k), max(1, 6 - k // 4))
    if kind == "rise":
        return chat(min(3500.0, hz / 0.96 ** k), vol(k, ((24, 5), (999, 6))))
    raise SystemExit("no chatter voice for %r" % kind)


def steps(evs, ch, octaves):
    out = []
    for fc in (ch1(e, octaves) if ch == 0 else ch2(e) for e in evs):
        if out and tuple(out[-1][:3]) == fc and out[-1][3] < MAXN:
            out[-1][3] += 1
        else:
            out.append([fc[0], fc[1], fc[2], 1])
    return tuple(tuple(s) for s in out)


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    octaves = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    song = mus.parse(src)
    subs = [{}, {}]                     # steps -> index
    order = [[], []]
    for name in song.order:
        lens = set()
        for ch in (0, 1):
            evs = mus.frames(song, name, ch + 1)
            lens.add(len(evs))
            st = steps(evs, ch, octaves)
            if st not in subs[ch]:
                subs[ch][st] = len(subs[ch])
            order[ch].append(subs[ch][st])
        if len(lens) != 1:
            raise SystemExit("%s: pattern %s's channels differ in length" % (src, name))
    if max(len(subs[0]), len(subs[1])) > 255 or len(song.order) > 254:
        raise SystemExit("mkmus_ay: too many patterns")

    out = ["/* GENERATED by tools/mkmus_ay.py from %s: edit that, not this. */" % src,
           "/* Steps: lo, hi, volume, jiffies (0 ends); hi $80: channel C's noise (src/nabu/sound.c). */",
           "#include <stdint.h>", ""]
    size = 0
    for ch in (0, 1):
        for st, i in subs[ch].items():
            body = [b for s in st for b in s] + [0, 0, 0, 0]
            size += len(body)
            out.append("static const uint8_t m%d_%d[] = {" % (ch + 1, i))
            for j in range(0, len(body), 16):
                out.append("    " + ", ".join("%d" % b for b in body[j:j + 16]) + ",")
            out.append("};")
        out.append("const uint8_t *const m_sub%d[] = { %s };" %
                   (ch + 1, ", ".join("m%d_%d" % (ch + 1, i) for i in range(len(subs[ch])))))
        out.append("const uint8_t m_ord%d[] = { %s, 255 };" % (ch + 1, ", ".join(str(i) for i in order[ch])))
        out.append("")
        size += 2 * len(subs[ch]) + len(order[ch]) + 1
    out.append("const uint8_t m_loop = %d;" % song.loop)
    out.append("")
    os.makedirs(outdir, exist_ok=True)
    open(os.path.join(outdir, "music.c"), "w").write("\n".join(out))
    print("%s/music.c: %d + %d patterns, %d bytes" % (outdir, len(subs[0]), len(subs[1]), size))


if __name__ == "__main__":
    main()
